'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('../browser/node_modules/typescript');
const source = fs.readFileSync('browser/src/workspace-recovery.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {}, require: name => { assert.equal(name, 'react'); return {}; } };
vm.runInNewContext(compiled, sandbox);
const { WorkspaceRecovery } = sandbox.exports;
const recovery = new WorkspaceRecovery();
assert.throws(() => recovery.bind('invalid'));
recovery.bind('a'.repeat(64));
const slot = recovery.slot('group:form');
const file = { name: 'synthetic-only.pdf', bytes: [1, 2, 3] };
const submission = { key: 'same-request', path: 'cases/create/', values: { note: 'Synthetic' }, files: [file] };
slot.patch({ values: { note: 'Synthetic' }, submission });
recovery.bind('a'.repeat(64));
assert.equal(recovery.slot('group:form').read().submission, submission, 'Same current owner resumes exact request and file objects');
recovery.bind('b'.repeat(64));
assert.equal(Object.keys(recovery.slot('group:form').read()).length, 0);
slot.patch({ values: { note: 'stale callback' } });
assert.equal(Object.keys(recovery.slot('group:form').read()).length, 0, 'Previous owner cannot repopulate memory');
const current = recovery.slot('group:form'); current.patch({ submission });
recovery.clear(); current.patch({ submission });
assert.equal(Object.keys(recovery.slot('group:form').read()).length, 0, 'Explicit logout/discard invalidates pending callbacks');
const old = recovery.slot('group:form'); old.patch({ submission });
recovery.slot('other:form'); old.patch({ submission });
assert.equal(Object.keys(recovery.slot('other:form').read()).length, 0, 'One bounded task; no cross-workspace data');
assert.equal(/localStorage|sessionStorage|indexedDB/.test(source), false);
console.log('Workspace recovery: owner/task isolation, explicit clearing, exact retry and stale callback checks passed.');
